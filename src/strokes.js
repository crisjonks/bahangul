const plen = p => p.reduce((s, q, i) => i ? s + Math.hypot(q[0] - p[i-1][0], q[1] - p[i-1][1]) : 0, 0);
function rs(pts, n = 24) {
  const d = [0]; for (let i = 1; i < pts.length; i++) d[i] = d[i-1] + Math.hypot(pts[i][0] - pts[i-1][0], pts[i][1] - pts[i-1][1]);
  const T = d[d.length - 1] || 1, o = [];
  for (let k = 0; k < n; k++) { const t = T * k / (n - 1); let j = 1; while (j < d.length - 1 && d[j] < t) j++; const f = (t - d[j-1]) / ((d[j] - d[j-1]) || 1); o.push([pts[j-1][0] + (pts[j][0] - pts[j-1][0]) * f, pts[j-1][1] + (pts[j][1] - pts[j-1][1]) * f]); }
  return o;
}
const md = (a, b) => a.reduce((s, p, i) => s + Math.hypot(p[0] - b[i][0], p[1] - b[i][1]), 0) / a.length;
// Compares one drawn stroke (points in 0-100 units) with the expected stroke. Returns 'ok' | 'rev' | 'short' | 'bad'.
export function judge(user, tpl) {
  if (user.length < 2 || plen(user) < 6) return 'short';
  const a = rs(user), b = rs(tpl), closed = Math.hypot(tpl[0][0] - tpl[tpl.length-1][0], tpl[0][1] - tpl[tpl.length-1][1]) < 4;
  if (closed) { let best = 1e9; for (let s = 0; s < 24; s++) for (const d of [1, -1]) { const c = a.map((_, i) => b[((d * i + s) % 24 + 24) % 24]); best = Math.min(best, md(a, c)); } return best < 14 && plen(user) > plen(tpl) * .6 ? 'ok' : 'bad'; }
  const L = plen(tpl), r = plen(user) / L, th = Math.min(14, Math.max(8, L * .5 + 3)), sd = Math.min(24, L * .6 + 6);
  if (r < .45 || r > (L < 25 ? 3.2 : 1.9)) return 'bad';
  if (md(a, b) < th && Math.hypot(a[0][0] - b[0][0], a[0][1] - b[0][1]) < sd) return 'ok';
  return md(a, [...b].reverse()) < th ? 'rev' : 'bad';
}
